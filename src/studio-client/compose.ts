export function composeLocal(input: DraftInput): ShortPlan {
  const n = sceneCount(input.seconds);
  const built = beats(input.style, input.topic);
  const label = styleLabel(input.style);
  return {
    topic: input.topic,
    style: input.style,
    seconds: input.seconds,
    title: `${input.topic} — ${label} ใน ${input.seconds} วินาที`,
    description: `คลิปสั้นแนว${label} เรื่อง${input.topic} สรุปให้จบใน ${input.seconds} วินาที อ่านบนจอได้โดยไม่ต้องเปิดเสียง`,
    hashtags: ["#Shorts", "#YouTubeShorts", "#คลิปสั้น", "#ความรู้"],
    scenes: pack(built.hook, built.middles, built.cta, n),
    imagePrompt: `Cinematic vertical still life about ${input.topic}, natural light, shallow depth, no text, no logo, no watermark`,
    source: "local",
  };
}

