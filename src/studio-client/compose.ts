import { sceneCount, styleLabel, type DraftInput, type Scene, type ShortPlan, type StyleId } from "./types.js";

function scene(kicker: string, caption: string, narration: string): Scene {
  return { kicker, caption, narration };
}

function pack(hook: Scene, middles: Scene[], cta: Scene, n: number): Scene[] {
  const mid: Scene[] = [];
  while (mid.length < Math.max(0, n - 2)) {
    mid.push(middles[mid.length % middles.length]);
  }
  return [hook, ...mid, cta].slice(0, n);
}

